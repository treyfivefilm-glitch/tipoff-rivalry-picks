import { createClient } from "@supabase/supabase-js";
const url = process.env["SUPABASE_URL"];
const key = process.env["SUPABASE_PUBLISHABLE_KEY"];
if (!url || !key) throw new Error("Missing test configuration");
const client = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
const day = new Intl.DateTimeFormat("en-CA", { timeZone:"America/Los_Angeles", year:"numeric", month:"2-digit", day:"2-digit" }).format(new Date());
const { data: signed, error: loginError } = await client.auth.signInAnonymously();
if (loginError || !signed.session) throw new Error("Test guest login failed: " + loginError?.message);
console.log("Test user authenticated; checking real NBA feed for " + day);
const { data, error } = await client.functions.invoke("sync-games", { body: { days: [day], force:true } });
if (error) throw new Error("NBA sync function failed: " + error.message);
console.log("NBA sync result:", JSON.stringify(data));
if (!data || data.errors?.length || data.updated < 1) throw new Error("NBA feed did not write games");
const { data: allGames, error: queryError } = await client.from("games").select("away_code,home_code,state,away_score,home_score,start_utc").gte("start_utc", day+"T00:00:00Z").lt("start_utc", new Date(Date.parse(day+"T00:00:00Z")+2*86400000).toISOString());
if (queryError) throw new Error("Cannot query stored games: " + queryError.message);
const scored = (allGames || []).filter(g => (g.state === "final" || g.state === "live") && g.away_score !== null && g.home_score !== null);
console.log("Games returned:", allGames?.length ?? 0, "live or final with scores:", scored.length);
if (!scored.length) throw new Error("NBA live scores are not stored after refresh");
console.log("Verified scores:", scored.slice(0,3).map(g => g.away_code+" "+g.away_score+" @ "+g.home_code+" "+g.home_score+" ("+g.state+")").join("; "));
await client.auth.signOut();
